/// Width of one glyph cell plus spacing, in grid units.
const ADVANCE: f32 = 5.6;
const SPACE: f32 = 3.5;

fn unit(size: f32) -> f32 {
    size / 7.5
}

pub fn headline_width(s: &str, size: f32) -> f32 {
    let u = unit(size);
    let w: f32 = s
        .chars()
        .map(|c| if c == ' ' { SPACE } else { ADVANCE })
        .sum();
    (w - (ADVANCE - 4.0)) * u
}

fn strokes(strokes: &[Stroke], ox: f32, oy: f32, u: f32, thick: f32, c: Color) {
    for poly in strokes {
        for (i, &(x, y)) in poly.iter().enumerate() {
            let p = vec2(ox + x * u, oy + y * u);
            draw_circle(p.x, p.y, thick * 0.5, c);
            if let Some(&(nx, ny)) = poly.get(i + 1) {
                draw_line(p.x, p.y, ox + nx * u, oy + ny * u, thick, c);
            }
        }
    }
}

fn glossy_glyph(ch: char, x: f32, top: f32, u: f32, base: Color, alpha: f32) {
    let g = glyph(ch);
    let th = u * 1.25;
    let shadow = Color::new(0.08, 0.0, 0.2, 0.45 * alpha);
    strokes(g, x + u * 0.45, top + u * 0.55, u, th + u * 0.7, shadow);
    strokes(
        g,
        x,
        top,
        u,
        th + u * 0.7,
        with_alpha(darken(base, 0.6), alpha),
    );
    strokes(g, x, top, u, th, with_alpha(base, alpha));
    strokes(
        g,
        x - u * 0.12,
        top - u * 0.16,
        u,
        th * 0.4,
        with_alpha(lighten(base, 0.65), 0.85 * alpha),
    );
}

/// Draws a glossy headline centred on `cx` with its baseline at `y`.
pub fn headline(s: &str, cx: f32, y: f32, size: f32, color: Color) {
    let u = unit(size);
    let mut x = cx - headline_width(s, size) * 0.5;
    let top = y - 6.0 * u;
    for ch in s.chars() {
        if ch == ' ' {
            x += SPACE * u;
            continue;
        }
        glossy_glyph(ch.to_ascii_uppercase(), x, top, u, color, color.a);
        x += ADVANCE * u;
    }
}

/// Multi-coloured, bobbing headline used for titles and celebrations.
pub fn fancy_headline(s: &str, cx: f32, y: f32, size: f32, t: f32) {
    let u = unit(size);
    let mut x = cx - headline_width(s, size) * 0.5;
    let top = y - 6.0 * u;
    for (i, ch) in s.chars().enumerate() {
        if ch == ' ' {
            x += SPACE * u;
            continue;
        }
        let bob = (t * 3.0 + i as f32 * 0.6).sin() * size * 0.05;
        glossy_glyph(
            ch.to_ascii_uppercase(),
            x,
            top + bob,
            u,
            orb_color(i as u8),
            1.0,
        );
        x += ADVANCE * u;
    }
}
